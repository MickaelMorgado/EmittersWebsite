YOUTUBE_URL = "{{YOUTUBE_URL}}"
TARGET_LANG = "{{TARGET_LANG}}"
WHISPER_MODEL = "base"  # tiny, base, small, medium, large
ORIGINAL_VOLUME = 0.2  # Original audio volume (0-1)
OUTPUT_DIR = str(Path.home() / "Desktop")  # Output to Desktop

